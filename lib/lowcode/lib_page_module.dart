  (宿主 loc.assign ((网址 文字)) -> 空)
  (宿主 page.alert ((话 文字)) -> 空)
  (宿主 page.confirm ((话 文字)) -> 是否)
  (宿主 compat.num ((值 任意)) -> 小数)
