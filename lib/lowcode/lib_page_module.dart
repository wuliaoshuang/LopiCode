  (宿主 page.state.derived ((算法 (不等函数 () 任意))) -> 任意)
  (宿主 page.state.watch ((取值 (不等函数 () 任意)) (做法 (要等函数 (任意 任意) 空))) -> (函数 () 空))
  (宿主 page.ui.read ((控件 文字) (属性 文字)) -> 任意)
  (宿主 page.ui.write ((控件 文字) (属性 文字) (值 任意)) -> 空)
  (宿主 page.ui.on ((控件 文字) (事件 文字) (做法 (要等函数 ((字典 任意)) 空)) (选项 (字典 任意))) -> (函数 () 空))
  (宿主 page.ui.life ((时刻 文字) (做法 (要等函数 (任意) 空))) -> 空)
  (宿主 timer.after ((毫秒 小数) (做法 (要等函数 () 空))) -> 整数)
