    (做 (宿 page.ui.on 控件 种类 做法 选项))))
  (公开 (函数 事件的值 ((e 事件)) -> 文字 (返回 (文 (取 e "value")))))
  (公开 (函数 事件的键 ((e 事件)) -> 文字 (返回 (文 (取 e "key")))))

  ; —— 页面的时刻 ——
