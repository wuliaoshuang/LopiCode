  (公开 (函数 旧真 ((值 任意)) -> 是否 (返回 (宿 compat.truthy 值))))
  (公开 (函数 旧等 ((甲 任意) (乙 任意)) -> 是否 (返回 (宿 compat.eq 甲 乙))))
