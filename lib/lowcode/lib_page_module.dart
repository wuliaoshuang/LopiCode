  (公开 (函数 读格子 ((格子 任意)) -> 任意 (返回 (宿 page.state.read 格子))))
  (公开 (函数 写格子 ((格子 任意) (值 任意)) (做 (宿 page.state.write 格子 值))))
  (公开 (函数 派生格子 ((算法 (不等函数 () 任意))) -> 任意 (返回 (宿 page.state.derived 算法))))
