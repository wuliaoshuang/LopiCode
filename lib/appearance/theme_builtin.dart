  'section': _c(red),
  'name': _c(red),
  'selector-tag': _c(red),
  'deletion': _c(red),
  'subst': _c(red),
  'literal': _c(cyan),
  'string': _c(green),
  'regexp': _c(green),
  'addition': _c(green),
  'attribute': _c(green),
  'attr': _c(orange),
  'variable': _c(orange),
  'template-variable': _c(orange),
  'type': _c(orange),
  'selector-class': _c(orange),
  'selector-attr': _c(orange),
  'selector-pseudo': _c(orange),
  'number': _c(orange),
  'symbol': _c(blue),
  'bullet': _c(blue),
  'link': _c(blue),
  'meta': _c(blue),
  'selector-id': _c(blue),
  'title': _c(blue),
  'built_in': _c(yellow),
  // 其余的分类默认不单独上色（跟代码文字一个色）——加主题系统之前就是这样。
  for (final f in kTokenFields)
    if (!_atomKeys.contains(f.key)) f.key: const TokenStyle(),
};

