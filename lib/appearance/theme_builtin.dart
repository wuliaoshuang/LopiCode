TokenStyle _c(int color) => TokenStyle(color: color);

/// 默认的高亮配色：Atom One（re_highlight 自带的那两张表），只上色、不加粗不倾斜。
Map<String, TokenStyle> _atomTokens({
  required int comment,
  required int purple,
  required int red,
  required int cyan,
  required int green,
  required int orange,
  required int blue,
  required int yellow,
}) => {
  'comment': _c(comment),
  'quote': _c(comment),
  'doctag': _c(purple),
  'keyword': _c(purple),
