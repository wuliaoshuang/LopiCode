/// 判断一段代码是哪种语言（文件图标、编辑器高亮、只读代码查看共用这一个入口）。
class CodeHighlighter {
  /// 按文件名 / 扩展名判断。不认识的返回 'text'（不高亮）。
  static String languageFor(String path) {
    final name = path.split(RegExp(r'[/\\]')).last.toLowerCase();
    final byName = switch (name) {
      'dockerfile' || 'containerfile' => 'dockerfile',
      'makefile' || 'gnumakefile' => 'makefile',
      'cmakelists.txt' => 'cmake',
      'gemfile' || 'rakefile' || 'podfile' => 'ruby',
      '.gitignore' || '.dockerignore' || '.npmrc' || '.editorconfig' || '.env' => 'ini',
      'nginx.conf' => 'nginx',
      '.htaccess' || 'httpd.conf' => 'apache',
      '.vimrc' => 'vim',
      _ => null,
    };
    if (byName != null) return byName;
    if (name.startsWith('dockerfile.') || name.endsWith('.dockerfile')) return 'dockerfile';
    final ext = name.contains('.') ? name.split('.').last : '';
    return switch (ext) {
      'html' || 'htm' || 'xml' || 'svg' || 'xhtml' || 'plist' || 'csproj' || 'xaml' => 'html',
      'vue' => 'vue',
      'css' => 'css',
      'scss' => 'scss',
      'less' => 'less',
      'js' || 'mjs' || 'cjs' || 'jsx' => 'js',
      'ts' || 'mts' || 'cts' || 'tsx' => 'ts',
      'json' || 'jsonc' || 'json5' || 'webmanifest' => 'json',
      'dart' => 'dart',
      'md' || 'markdown' => 'md',
      'yml' || 'yaml' => 'yaml',
      'sh' || 'bash' || 'zsh' => 'sh',
      'kt' || 'kts' => 'kotlin',
      'py' || 'pyw' => 'python',
      'go' => 'go',
      'java' => 'java',
      'php' => 'php',
      'cs' => 'csharp',
      'rs' => 'rust',
      'rb' => 'ruby',
      'c' || 'h' => 'c',
      'cc' || 'cpp' || 'cxx' || 'hpp' || 'hh' || 'hxx' => 'cpp',
      'sql' => 'sql',
      'toml' || 'ini' || 'cfg' || 'conf' || 'env' => 'ini',
      'properties' => 'properties',
      'gradle' => 'gradle',
      'groovy' => 'groovy',
      'swift' => 'swift',
      'm' || 'mm' => 'objectivec',
      'lua' => 'lua',
      'pl' || 'pm' => 'perl',
      'r' => 'r',
      'scala' || 'sc' => 'scala',
      'mk' => 'makefile',
      'cmake' => 'cmake',
      'diff' || 'patch' => 'diff',
      'ps1' || 'psm1' => 'powershell',
      'bat' || 'cmd' => 'bat',
      'graphql' || 'gql' => 'graphql',
      'proto' => 'protobuf',
      'hs' => 'haskell',
      'ex' || 'exs' => 'elixir',
      'erl' || 'hrl' => 'erlang',
      'clj' || 'cljs' || 'cljc' || 'edn' => 'clojure',
      'jl' => 'julia',
      'fs' || 'fsx' || 'fsi' => 'fsharp',
      'vb' => 'vbnet',
      'ml' || 'mli' => 'ocaml',
      'nim' || 'nims' => 'nim',
      'tex' || 'sty' || 'cls' => 'latex',
      'pas' || 'dpr' => 'delphi',
      'lisp' || 'lsp' || 'el' => 'lisp',
      'scm' || 'ss' || 'rkt' => 'scheme',
      'elm' => 'elm',
      'cr' => 'crystal',
      'coffee' => 'coffeescript',
      'styl' => 'stylus',
      'hbs' || 'handlebars' || 'mustache' => 'handlebars',
      'twig' => 'twig',
      'erb' => 'erb',
      'haml' => 'haml',
      'jinja' || 'jinja2' || 'j2' || 'njk' => 'django',
      'nix' => 'nix',
      'vim' => 'vim',
      'tcl' => 'tcl',
      'awk' => 'awk',
      'http' || 'rest' => 'http',
      'htaccess' => 'apache',
      'qml' => 'qml',
      'ino' => 'arduino',
      'wat' || 'wast' => 'wasm',
      'v' || 'sv' || 'svh' => 'verilog',
      'vhd' || 'vhdl' => 'vhdl',
      'f90' || 'f95' || 'f03' || 'f' => 'fortran',
      'thrift' => 'thrift',
      'pro' => 'prolog',
      'pgsql' || 'psql' => 'pgsql',
      'glsl' || 'vert' || 'frag' => 'glsl',
      'asm' || 's' => 'x86asm',
      'hx' => 'haxe',
      'd' => 'd',
      'vala' => 'vala',
      'dts' || 'dtsi' => 'dts',
      'll' => 'llvm',
      'smali' => 'smali',
      'pp' => 'puppet',
      'adoc' || 'asciidoc' => 'asciidoc',
      'matlab' => 'matlab',
      _ => 'text',
    };
  }
}
